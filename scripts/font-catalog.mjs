import { readFile, writeFile } from 'node:fs/promises';
import { create } from 'fontkit';
import { FONT_CATALOG } from '../src/domain/fonts.ts';
import { absolute, hash } from './lib.mjs';

// Font parsing is build-time only. VORG or vmtx supplies the vertical origin;
// the browser uses the same bundled bytes and the generated outlines.
const variants = {}, advances = {}, coverage = {};
for (const entry of FONT_CATALOG.filter(font => font.family !== 'Book Mincho')) {
  const bytes = await readFile(absolute('public/' + entry.path)), font = create(bytes);
  if (hash(bytes) !== entry.sha256) throw Error('Font changed: ' + entry.name);
  const vorg = font.VORG;
  // fontkit 2.0.4 reads vhea.version as uint16 instead of Fixed, shifting
  // numberOfMetrics by two bytes. Read this header from its decoded tables.
  void font.unitsPerEm;
  const bytesOfTables=Buffer.from(font.stream.buffer),vhea=font.directory.tables.vhea,vmtx=font.directory.tables.vmtx;
  if(!vorg&&(!vhea||!vmtx))throw Error('Vertical metrics missing: '+entry.name);
  const count=vhea?bytesOfTables.readUInt16BE(vhea.offset+34):0,loca=font.loca?.offsets;
  if(vhea&&![0x00010000,0x00011000].includes(bytesOfTables.readUInt32BE(vhea.offset)))throw Error('Unsupported vhea header: '+entry.name);
  if(!vorg&&(!count||count>font.numGlyphs||vmtx.length<count*4+(font.numGlyphs-count)*2))throw Error('Invalid vertical metrics: '+entry.name);
  const explicit = new Map(vorg?.metrics.map(row => [row.glyphIndex, row.vertOriginY]) ?? []);
  const originOf = glyph => {
    if (vorg) return explicit.get(glyph.id) ?? vorg.defaultVertOriginY;
    const offset=vmtx.offset+(glyph.id<count?glyph.id*4+2:count*4+(glyph.id-count)*2),bearing=bytesOfTables.readInt16BE(offset);
    // Empty glyf entries have no box; fontkit's cbox reads the following glyph.
    const empty=loca&&loca[glyph.id]===loca[glyph.id+1];
    return (empty?0:Number.isFinite(glyph.cbox.maxY)?glyph.cbox.maxY:0)+bearing;
  };
  const allOrigins = new Map(), frequencies = new Map();
  for (const cp of font.characterSet) {
    const origin = originOf(font.glyphForCodePoint(cp));
    if (!Number.isFinite(origin)) throw Error('Invalid origin: ' + cp);
    allOrigins.set(cp, origin); frequencies.set(origin, (frequencies.get(origin) ?? 0) + 1);
  }
  const origin = vorg?.defaultVertOriginY ?? [...frequencies].sort((a,b) => b[1]-a[1])[0][0], glyphs = {}, origins = {};
  for (const cp of font.characterSet) {
    const char = String.fromCodePoint(cp), glyph = font.glyphForCodePoint(cp), alternate = font.layout(char, ['vert']).glyphs;
    if (allOrigins.get(cp) !== origin) origins[char] = allOrigins.get(cp);
    if (alternate.length === 1 && alternate[0].id !== glyph.id) glyphs[char] = [alternate[0].path.toSVG(), originOf(alternate[0])];
  }
  if (!glyphs['「'] || !glyphs['、'] || !glyphs['ぁ'] || !glyphs['ー']) throw Error('Vertical alternates missing: ' + entry.name);
  variants[entry.family] = { units:font.unitsPerEm, origin, glyphs, origins };
  const ranges=[];
  for(const cp of [...font.characterSet].sort((a,b)=>a-b)){const last=ranges.at(-1);if(last&&last[1]+1===cp)last[1]=cp;else ranges.push([cp,cp]);}
  coverage[entry.family]=ranges;
  advances[entry.family] = Object.fromEntries(Array.from({length:95}, (_,i) => String.fromCodePoint(32+i)).map(char => [char, font.glyphForCodePoint(char.codePointAt(0)).advanceWidth/font.unitsPerEm]));
}
const outputs = {
  'public/font-faces.css': FONT_CATALOG.filter(font=>font.family!=='Book Mincho').map(font=>`@font-face{font-family:'${font.family}';src:url('./${font.path}') format('${font.format}');font-style:normal;font-weight:400;font-display:block}`).join('\n')+'\n',
  'src/render/font-variants.ts': '/** Generated by scripts/font-catalog.mjs from the bundled OFL fonts. */\nimport type { FontData } from "./font-data.js";\nexport const FONT_VARIANTS: Readonly<Record<string, FontData>> = ' + JSON.stringify(variants) + ';\n',
  'src/domain/font-advances.ts': '/** Generated by scripts/font-catalog.mjs. Units are em. */\nexport const FONT_ADVANCES: Readonly<Record<string, Readonly<Record<string, number>>>> = ' + JSON.stringify(advances) + ';\nexport const FONT_COVERAGE: Readonly<Record<string, readonly (readonly [number,number])[]>> = '+JSON.stringify(coverage)+';\n',
};
for (const [file, source] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) { if (await readFile(absolute(file),'utf8') !== source) throw Error('Stale font data: ' + file); }
  else await writeFile(absolute(file), source);
}
console.log('Bundled font outlines, origins and advances verified: ' + Object.keys(variants).length);
